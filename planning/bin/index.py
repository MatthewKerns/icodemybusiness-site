#!/usr/bin/env python3
"""Rebuild planning/transcripts/INDEX.md from each transcript file's frontmatter.

Usage: python3 planning/bin/index.py   (from the repo root; no dependencies)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "transcripts"
FIELDS = ("id", "source", "date_local", "duration_min", "participants", "relevance", "fidelity", "topics", "url")


def frontmatter(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    out: dict[str, str] = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip().strip('"')
    return out


def main() -> int:
    if not ROOT.is_dir():
        print(f"no {ROOT}", file=sys.stderr)
        return 1
    rows = []
    for p in sorted(ROOT.glob("*.md")):
        if p.name in ("INDEX.md",) or p.name.startswith("_"):
            continue
        fm = frontmatter(p)
        if not fm.get("id"):
            print(f"skip (no frontmatter): {p.name}", file=sys.stderr)
            continue
        rows.append((fm.get("date_local", ""), p.name, fm))
    rows.sort()

    skipped = []
    for p in sorted(ROOT.glob("_skipped_*.md")):
        for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.strip() and not line.startswith("#"):
                skipped.append(line.strip())

    lines = [
        "# Planning transcripts — chronological index",
        "",
        f"Generated by `planning/bin/index.py`. {len(rows)} stored, {len(skipped)} skipped.",
        "Local Pacific time. `relevance` is to the business plan (yes / partly / no).",
        "",
        "| date (PT) | source | min | participants | relevance | fidelity | topics | file | link |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for date_local, name, fm in rows:
        lines.append(
            "| {d} | {s} | {m} | {p} | {r} | {f} | {t} | [{n}]({n}) | [open]({u}) |".format(
                d=date_local,
                s=fm.get("source", ""),
                m=fm.get("duration_min", ""),
                p=fm.get("participants", "").strip("[]"),
                r=fm.get("relevance", ""),
                f=fm.get("fidelity", "copied").split()[0],
                t=fm.get("topics", "").strip("[]"),
                n=name,
                u=fm.get("url", ""),
            )
        )
    if skipped:
        lines += ["", "## Skipped (not stored)", "", "| date | id | why |", "|---|---|---|"]
        lines += sorted(skipped)
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"INDEX.md: {len(rows)} stored, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
